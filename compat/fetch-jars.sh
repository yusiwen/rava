#!/usr/bin/env bash
#
# Fetch and verify the pinned jar set for the rava target.
#
#   bash compat/fetch-jars.sh               fetch compat/jars/, then verify against the lock
#   bash compat/fetch-jars.sh --write-lock  fetch compat/jars/ and rewrite compat/jars.lock
#   bash compat/fetch-jars.sh --check       verify compat/jars/ against the lock (no fetch)
#
# Fetching needs JAVA_HOME (the pinned build JDK) and Maven (MVN, or `mvn` on PATH):
#
#   JAVA_HOME=/path/to/jdk MVN=/path/to/mvn bash compat/fetch-jars.sh
#
# The set is the reference application's runtime class path plus its own thin jar.
# Versions come from reference-app/pom.xml (Spring Boot 3.5.16 -> Spring 6.2.19,
# Tomcat 10.1.55), never from this script.
#
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
JARS_DIR="$ROOT/compat/jars"
LOCK_FILE="$ROOT/compat/jars.lock"
TARGETS="$ROOT/compat/targets.toml"
POM="$ROOT/reference-app/pom.xml"
BUILD_DIR="$ROOT/reference-app/target"

MODE=fetch
case "${1:-}" in
  "") ;;
  --check) MODE=check ;;
  --write-lock) MODE=write-lock ;;
  -h | --help)
    sed -n '2,17p' "${BASH_SOURCE[0]}"
    exit 0
    ;;
  *)
    echo "error: unknown argument: ${1}" >&2
    exit 2
    ;;
esac
[[ $# -le 1 ]] || {
  echo "error: too many arguments" >&2
  exit 2
}

die() {
  echo "error: $*" >&2
  exit 1
}

# Reads `count = N` from the lock file.
read_declared_count() {
  local count
  count=$(sed -n 's/^[[:space:]]*count[[:space:]]*=[[:space:]]*\([0-9][0-9]*\)[[:space:]]*$/\1/p' "$LOCK_FILE")
  [[ -n "$count" ]] || die "compat/jars.lock has no count line"
  printf '%s\n' "$count"
}

# Verifies compat/jars/ against compat/jars.lock: count, names and sha256.
verify() {
  [[ -d "$JARS_DIR" ]] || die "missing jar directory compat/jars; run: bash compat/fetch-jars.sh"
  [[ -f "$LOCK_FILE" ]] || die "missing lock file compat/jars.lock"

  local declared entries=0 line hash name actual failures=0
  local -A pinned=()
  declared=$(read_declared_count)

  while IFS= read -r line; do
    line=${line%$'\r'}
    [[ -z "${line//[[:space:]]/}" || "$line" == '#'* ]] && continue
    [[ "$line" =~ ^[[:space:]]*count[[:space:]]*= ]] && continue
    if [[ ! "$line" =~ ^([0-9a-f]{64})[[:space:]]+([^[:space:]]+\.jar)[[:space:]]*$ ]]; then
      die "malformed compat/jars.lock entry: $line"
    fi
    hash=${BASH_REMATCH[1]}
    name=${BASH_REMATCH[2]}
    [[ -z "${pinned[$name]+set}" ]] || die "duplicate compat/jars.lock entry: $name"
    pinned[$name]=$hash
    entries=$((entries + 1))
  done <"$LOCK_FILE"

  [[ "$entries" -eq "$declared" ]] ||
    die "compat/jars.lock declares $declared jars but lists $entries"

  for name in "${!pinned[@]}"; do
    if [[ ! -f "$JARS_DIR/$name" ]]; then
      echo "missing:  $name" >&2
      failures=$((failures + 1))
      continue
    fi
    actual=$(sha256sum "$JARS_DIR/$name" | cut -d' ' -f1)
    if [[ "$actual" != "${pinned[$name]}" ]]; then
      echo "checksum: $name" >&2
      echo "  expected ${pinned[$name]}" >&2
      echo "  actual   $actual" >&2
      failures=$((failures + 1))
    fi
  done

  local path base
  while IFS= read -r -d '' path; do
    base=${path##*/}
    if [[ -z "${pinned[$base]+set}" ]]; then
      echo "unexpected jar: $base" >&2
      failures=$((failures + 1))
    fi
  done < <(find "$JARS_DIR" -maxdepth 1 -type f -name '*.jar' -print0)

  while IFS= read -r -d '' path; do
    echo "unexpected directory inside compat/jars: ${path##*/}" >&2
    failures=$((failures + 1))
  done < <(find "$JARS_DIR" -mindepth 1 -maxdepth 1 -type d -print0)

  [[ "$failures" -eq 0 ]] ||
    die "jar set does not match compat/jars.lock ($failures problem(s))"
  echo "ok: $entries jars match compat/jars.lock"
}

# Writes compat/jars.lock from the current contents of compat/jars/.
write_lock() {
  [[ -d "$JARS_DIR" ]] || die "missing jar directory compat/jars"

  local -a names=()
  local name path
  while IFS= read -r -d '' path; do
    names+=("${path##*/}")
  done < <(find "$JARS_DIR" -maxdepth 1 -type f -name '*.jar' -print0)
  [[ ${#names[@]} -gt 0 ]] || die "no jars in compat/jars"

  mapfile -t names < <(printf '%s\n' "${names[@]}" | LC_ALL=C sort)

  local tmp="$LOCK_FILE.tmp"
  {
    echo "# rava pinned jar set - generated by compat/fetch-jars.sh --write-lock."
    echo "# One sha256 per jar; count must match [jars].count in compat/targets.toml."
    echo "# Regenerate after a target bump; the lock is part of the target."
    echo
    echo "count = ${#names[@]}"
    echo
    for name in "${names[@]}"; do
      (cd "$JARS_DIR" && sha256sum "$name")
    done
  } >"$tmp"
  mv "$tmp" "$LOCK_FILE"

  echo "wrote compat/jars.lock (${#names[@]} jars)"
  echo "set [jars].count = ${#names[@]} in compat/targets.toml for a new baseline"
}

# Fetches the runtime class path and the application jar into compat/jars/.
fetch() {
  [[ -n "${JAVA_HOME:-}" ]] || die "JAVA_HOME must point at the pinned build JDK"
  [[ -x "$JAVA_HOME/bin/java" ]] || die "JAVA_HOME/bin/java not found: $JAVA_HOME"
  local mvn="${MVN:-mvn}"
  command -v "$mvn" >/dev/null 2>&1 || die "mvn not found; set MVN=/path/to/mvn"

  local pinned actual
  pinned=$(sed -n 's/^[[:space:]]*source_sha256[[:space:]]*=[[:space:]]*"\([0-9a-f]\{64\}\)"[[:space:]]*$/\1/p' "$TARGETS")
  [[ -n "$pinned" ]] || die "compat/targets.toml has no reference_app.source_sha256"
  actual=$(bash "$ROOT/compat/source-hash.sh")
  [[ "$pinned" == "$actual" ]] ||
    die "reference-app source hashes to $actual, but compat/targets.toml pins $pinned; re-baseline the target"

  local app_version
  app_version=$(awk '
    /^\[reference_app\]/ { in_section = 1; next }
    /^\[/ { in_section = 0 }
    in_section && /^version[[:space:]]*=/ {
      sub(/^version[[:space:]]*=[[:space:]]*"/, "")
      sub(/".*$/, "")
      print
      exit
    }
  ' "$TARGETS")
  [[ -n "$app_version" ]] || die "compat/targets.toml has no reference_app.version"

  [[ "$JARS_DIR" == "$ROOT/compat/jars" ]] ||
    die "refusing to clean unexpected jar directory: $JARS_DIR"
  echo "fetching pinned jars into compat/jars"
  rm -rf "$JARS_DIR"
  mkdir -p "$JARS_DIR"

  JAVA_HOME="$JAVA_HOME" "$mvn" -B -ntp -f "$POM" clean package dependency:copy-dependencies \
    -DskipTests \
    -DincludeScope=runtime \
    -DoutputDirectory="$JARS_DIR"

  local app_jar="$BUILD_DIR/reference-app-${app_version}.jar"
  [[ -f "$app_jar" ]] || die "reference application jar not produced: $app_jar"
  cp "$app_jar" "$JARS_DIR/"
}

case "$MODE" in
  check)
    verify
    ;;
  fetch)
    fetch
    verify
    ;;
  write-lock)
    fetch
    write_lock
    verify
    ;;
esac
